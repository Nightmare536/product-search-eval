def main():
    with io.open(PATH, encoding="utf-8") as f:
        data = json.load(f)
    have = set(d.get("qid") for d in data)
    add = 0
    for i, (q, rel) in enumerate(HARD, 1):
        qid = "h%02d" % i
        if qid in have:
            continue
        data.append({"qid": qid, "query": q, "type": u"难例·纯意图", "relevant": rel})
        add += 1
    with io.open(PATH, "w", encoding="utf-8") as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=1))
    print(u"评测集：新增 %d 条难例，共 %d 条" % (add, len(data)))


if __name__ == "__main__":
    main()
